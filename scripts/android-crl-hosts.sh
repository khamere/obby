#!/usr/bin/env bash
# Rewrites the app's Android network security configs with the certificate
# verifier's list of CRL hosts. Those lists are served over plain http, so
# the app has to allow cleartext to them, and the app's config replaces the
# one the verifier ships. Run after bumping rustls-platform-verifier.
set -euo pipefail
cd "$(dirname "$0")/../src-tauri"

version=$(cargo tree --target aarch64-linux-android -e normal --prefix none --format '{p}' \
  | grep -oE 'rustls-platform-verifier-android v\S+' | head -1 | cut -d' ' -f2 | sed 's/^v//')
[ -n "$version" ] || { echo "rustls-platform-verifier-android not in the Android dependency tree" >&2; exit 1; }

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
curl -sfL -o "$tmp/verifier.aar" \
  "https://github.com/rustls/rustls-platform-verifier/raw/maven-archive/android-release-support/maven/org/rustls/rustls-platform-verifier/$version/rustls-platform-verifier-$version.aar"
unzip -q -o "$tmp/verifier.aar" res/xml/network_security_config.xml -d "$tmp"
domains=$(grep -oE '<domain [^>]*>[^<]+</domain>' "$tmp/res/xml/network_security_config.xml")
[ -n "$domains" ] || { echo "no CRL hosts in the verifier's config" >&2; exit 1; }

write() {
  local file=$1 cleartext=$2 note=$3
  {
    echo '<?xml version="1.0" encoding="utf-8"?>'
    echo "<!-- Generated by scripts/android-crl-hosts.sh from rustls-platform-verifier-android $version."
    echo "     $note -->"
    echo '<network-security-config>'
    echo "    <base-config cleartextTrafficPermitted=\"$cleartext\">"
    echo '        <trust-anchors>'
    echo '            <certificates src="system" />'
    echo '            <certificates src="user" />'
    echo '        </trust-anchors>'
    echo '    </base-config>'
    echo '    <!-- Certificate authorities publish their revocation lists over http,'
    echo '         and the verifier reads them to check the server certificate. -->'
    echo '    <domain-config cleartextTrafficPermitted="true">'
    echo "$domains" | sed 's/^/        /'
    echo '    </domain-config>'
    echo '</network-security-config>'
  } > "$file"
}

write gen/android/app/src/main/res/xml/network_security_config.xml false \
  "A CA the user installs on the phone is trusted too, so a private server with its own CA reaches the app the way it reaches a browser."
write gen/android/app/src/debug/res/xml/network_security_config.xml true \
  "A development build also talks to plain ws:// servers on the LAN."
echo "wrote $(echo "$domains" | wc -l) CRL hosts from verifier $version"
